-- Профили: свой — читать/обновлять; staff видит всех
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles
  for select using (id = auth.uid() or public.is_staff());

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
  for update using (id = auth.uid());

-- Когорты: читают все аутентифицированные; правит staff
drop policy if exists "cohorts_select_auth" on public.cohorts;
create policy "cohorts_select_auth" on public.cohorts
  for select using (auth.role() = 'authenticated');

drop policy if exists "cohorts_update_staff" on public.cohorts;
create policy "cohorts_update_staff" on public.cohorts
  for update using (public.is_staff());

drop policy if exists "cohort_schedule_select_auth" on public.cohort_schedule;
create policy "cohort_schedule_select_auth" on public.cohort_schedule
  for select using (auth.role() = 'authenticated');

drop policy if exists "cohort_schedule_write_staff" on public.cohort_schedule;
create policy "cohort_schedule_write_staff" on public.cohort_schedule
  for all using (public.is_staff());

-- Контент: published читают все (включая анонимов — нужен лендингу и туру);
-- черновики и запись — только staff
drop policy if exists "courses_select_published" on public.courses;
create policy "courses_select_published" on public.courses
  for select using (status = 'published' or public.is_staff());

drop policy if exists "courses_write_staff" on public.courses;
create policy "courses_write_staff" on public.courses
  for all using (public.is_staff());

drop policy if exists "modules_select_published" on public.course_modules;
create policy "modules_select_published" on public.course_modules
  for select using (
    exists (select 1 from public.courses c where c.id = course_id and (c.status = 'published' or public.is_staff()))
  );

drop policy if exists "modules_write_staff" on public.course_modules;
create policy "modules_write_staff" on public.course_modules
  for all using (public.is_staff());

drop policy if exists "blocks_select_published" on public.module_blocks;
create policy "blocks_select_published" on public.module_blocks
  for select using (
    exists (
      select 1 from public.course_modules m
      join public.courses c on c.id = m.course_id
      where m.id = module_id and (c.status = 'published' or public.is_staff())
    )
  );

drop policy if exists "blocks_write_staff" on public.module_blocks;
create policy "blocks_write_staff" on public.module_blocks
  for all using (public.is_staff());

-- Записи на курс: свои
drop policy if exists "enrollments_own" on public.enrollments;
create policy "enrollments_own" on public.enrollments
  for all using (user_id = auth.uid() or public.is_staff());

-- Прогресс: студент управляет своим, staff читает всё
drop policy if exists "progress_select" on public.progress;
create policy "progress_select" on public.progress
  for select using (user_id = auth.uid() or public.is_staff());

drop policy if exists "progress_insert_own" on public.progress;
create policy "progress_insert_own" on public.progress
  for insert with check (user_id = auth.uid());

drop policy if exists "progress_update_own" on public.progress;
create policy "progress_update_own" on public.progress
  for update using (user_id = auth.uid());

-- Сабмишены: читать свои (staff — все). INSERT-политики нет:
-- запись делает только edge-функция ai-gateway (service role, минуя RLS).
-- Так студент не может подделать score/status из консоли браузера.
drop policy if exists "submissions_select" on public.submissions;
create policy "submissions_select" on public.submissions
  for select using (user_id = auth.uid() or public.is_staff());

-- События тура: писать могут все (включая анонимов), читать — staff
drop policy if exists "tour_events_insert_any" on public.tour_events;
create policy "tour_events_insert_any" on public.tour_events
  for insert with check (true);

drop policy if exists "tour_events_select_staff" on public.tour_events;
create policy "tour_events_select_staff" on public.tour_events
  for select using (public.is_staff());

-- ai_calls / ai_cache: только service role (политик нет => deny всем остальным),
-- staff может смотреть расход
drop policy if exists "ai_calls_select_staff" on public.ai_calls;
create policy "ai_calls_select_staff" on public.ai_calls
  for select using (public.is_staff());

